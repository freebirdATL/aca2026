public class DoubleOperations{
    public static void main(String[] args) {
        double piston_of_a_car_engine; 
        double sleepy_joe;
        piston_of_a_car_engine = 1.32;
        sleepy_joe = 1.40;
        System.out.print(piston_of_a_car_engine + sleepy_joe + "\n");
        System.out.print(piston_of_a_car_engine - sleepy_joe + "\n");
        System.out.print(piston_of_a_car_engine * sleepy_joe + "\n");
        System.out.print(piston_of_a_car_engine / sleepy_joe + "\n");

    
    }
}