public class DoubleOperations {
    public static void main(String[] args) {
        double a1 = 6.7;
        double v8 = 2.7;
        System.out.print(a1 + v8 + "\n\n");
        System.out.print(a1 - v8 + "\n\n");
        System.out.print(a1 * v8 + "\n\n");
        System.out.print(a1 / v8 + "\n\n");
    }
}