public class DoubleOperations {
    public static void main(String[] args) {
        double t;
        double m;
        t = 2.49;
        m = 4.63;
        System.out.print(t + m + "\n");
        System.out.print(t - m + "\n");
        System.out.print(t * m + "\n");
        System.out.print(t / m + "\n");
    }
}